"""Evaluate on the held-out TEST session(s) (PRD 7.3, AC-1, AC-2).

    .venv\\Scripts\\python ml\\evaluate.py

Writes to ml/reports/: results.md (tables + acceptance checks),
metrics.json, confusion_<model>.csv/.png, misclassified.csv (windows the MLP
got wrong, with session/trial ids for the error analysis).
"""
import csv
import json
import os
import pickle
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from sklearn.metrics import confusion_matrix, f1_score, precision_recall_fscore_support  # noqa: E402

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import baseline  # noqa: E402
from common import LABELS, OUT, REPORTS  # noqa: E402
from train import load  # noqa: E402

L = [0, 1, 2, 3]


def smooth3(pred, meta_sess, meta_trial):
    """Majority of the last 3 windows within a trial (the firmware's smoothing)."""
    out = pred.copy()
    for i in range(len(pred)):
        hist = [pred[j] for j in range(max(0, i - 2), i + 1)
                if meta_sess[j] == meta_sess[i] and meta_trial[j] == meta_trial[i]]
        vals, cnt = np.unique(hist, return_counts=True)
        out[i] = vals[np.argmax(cnt)] if cnt.max() > 1 else pred[i]
    return out


def plot_cm(cm, title, path):
    fig, ax = plt.subplots(figsize=(4.6, 4.0), dpi=150)
    norm = cm / np.maximum(cm.sum(axis=1, keepdims=True), 1)
    ax.imshow(norm, cmap="Blues", vmin=0, vmax=1)
    for i in range(4):
        for j in range(4):
            ax.text(j, i, str(cm[i, j]), ha="center", va="center", color="white" if norm[i, j] > 0.5 else "black")
    ax.set_xticks(L, LABELS, rotation=30)
    ax.set_yticks(L, LABELS)
    ax.set_xlabel("predicted")
    ax.set_ylabel("true")
    ax.set_title(title, fontsize=10)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def main():
    F, y, meta = load()
    te = meta["split"] == "test"
    if not te.any():
        sys.exit("no test windows: check ml/split.yaml and run prepare.py")
    with open(os.path.join(OUT, "model.pkl"), "rb") as f:
        m = pickle.load(f)
    with open(os.path.join(OUT, "baseline.json"), encoding="utf-8") as f:
        th = json.load(f)
    Fe, ye = F[te], y[te]
    Z = (Fe - m["mu"]) / m["sd"]
    proba = m["mlp"].predict_proba(Z)
    preds = {"mlp": proba.argmax(axis=1), "tree": m["tree"].predict(Z), "baseline": baseline.predict(Fe, th)}
    preds["mlp_smooth3"] = smooth3(preds["mlp"], meta["session"][te], meta["trial"][te])

    os.makedirs(REPORTS, exist_ok=True)
    metrics = {}
    for name, p in preds.items():
        pr, rc, f1, sup = precision_recall_fscore_support(ye, p, labels=L, zero_division=0)
        cm = confusion_matrix(ye, p, labels=L)
        metrics[name] = {"macro_f1": float(f1_score(ye, p, average="macro", labels=L, zero_division=0)),
                         "accuracy": float((p == ye).mean()),
                         "per_class": {LABELS[i]: {"precision": float(pr[i]), "recall": float(rc[i]),
                                                   "f1": float(f1[i]), "support": int(sup[i])} for i in L},
                         "confusion": cm.tolist()}
        with open(os.path.join(REPORTS, f"confusion_{name}.csv"), "w", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            w.writerow(["true\\pred"] + LABELS)
            for i in L:
                w.writerow([LABELS[i]] + list(cm[i]))
        if name in ("mlp", "baseline"):
            plot_cm(cm, f"{name}: test macro-F1 {metrics[name]['macro_f1']:.3f}",
                    os.path.join(REPORTS, f"confusion_{name}.png"))
    with open(os.path.join(REPORTS, "metrics.json"), "w", encoding="utf-8") as f:
        json.dump(metrics, f, indent=2)

    wrong = np.flatnonzero(preds["mlp"] != ye)
    with open(os.path.join(REPORTS, "misclassified.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["session", "trial", "t0_ms", "true", "pred", "p_pred", "p_true"])
        for i in wrong:
            w.writerow([meta["session"][te][i], meta["trial"][te][i], meta["t0_ms"][te][i], LABELS[ye[i]],
                        LABELS[preds["mlp"][i]], f"{proba[i].max():.3f}", f"{proba[i][ye[i]]:.3f}"])

    mf = metrics["mlp"]
    min_rec = min(v["recall"] for v in mf["per_class"].values())
    ac1 = mf["macro_f1"] >= 0.85 and min_rec >= 0.75
    ac2 = mf["macro_f1"] > metrics["baseline"]["macro_f1"]
    sessions = ", ".join(sorted(set(meta["session"][te])))
    lines = ["# Results on the held-out test set", "",
             f"Generated by `ml/evaluate.py`. Test session(s): {sessions}; {len(ye)} windows. "
             "Window-level scores (2 s windows, 0.5 s hop, so neighbouring windows overlap).", "",
             "| Model | Macro-F1 | Accuracy | " + " | ".join(f"{c} recall" for c in LABELS) + " |",
             "|---|---|---|" + "---|" * 4]
    for name in ("baseline", "tree", "mlp", "mlp_smooth3"):
        mm = metrics[name]
        lines.append(f"| {name} | {mm['macro_f1']:.3f} | {mm['accuracy']:.3f} | "
                     + " | ".join(f"{mm['per_class'][c]['recall']:.2f}" for c in LABELS) + " |")
    lines += ["", "## MLP per class", "", "| Class | Precision | Recall | F1 | Windows |", "|---|---|---|---|---|"]
    for c in LABELS:
        pc = mf["per_class"][c]
        lines.append(f"| {c} | {pc['precision']:.3f} | {pc['recall']:.3f} | {pc['f1']:.3f} | {pc['support']} |")
    lines += ["", "## Acceptance criteria", "",
              f"* AC-1 (macro-F1 >= 0.85, every recall >= 0.75): macro-F1 {mf['macro_f1']:.3f}, lowest recall "
              f"{min_rec:.2f} -> **{'met' if ac1 else 'not met'}**",
              f"* AC-2 (MLP beats the baseline on macro-F1): {mf['macro_f1']:.3f} vs "
              f"{metrics['baseline']['macro_f1']:.3f} -> **{'met' if ac2 else 'not met'}**", "",
              f"Confusion matrices: `confusion_mlp.png`, `confusion_baseline.png` (counts; colour = row share). "
              f"{len(wrong)} misclassified MLP windows listed in `misclassified.csv`."]
    with open(os.path.join(REPORTS, "results.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines[4:10]))
    print(f"AC-1 {'met' if ac1 else 'NOT met'}, AC-2 {'met' if ac2 else 'NOT met'}")


if __name__ == "__main__":
    main()

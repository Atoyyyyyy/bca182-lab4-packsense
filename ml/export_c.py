"""Export the trained model, normalisation, baseline thresholds and golden
vectors as C headers (PRD 7.3, 7.4).

    .venv\\Scripts\\python ml\\export_c.py              (after train.py)
    .venv\\Scripts\\python ml\\export_c.py --placeholder (no model yet: firmware still builds)

Writes:
  src/model/model_params.h    sizes, class/feature names, z-score mean/std,
                              baseline thresholds, model version hash
  src/model/model_weights.h   MLP weights/biases, float32, [out][in] row-major
  test/golden/golden_vectors.h  up to 50 test windows (raw, as stored by the
                              capture log) + expected features, MLP probabilities
                              and baseline class, for `selftest model` (AC-3)
Tables are only defined where MODEL_DEFINE_TABLES / GOLDEN_DEFINE_TABLES is set
(one .c file each). Also checks that src/dsp/features.h uses the same DSP
constants as ml/common.py.
"""
import argparse
import datetime
import hashlib
import json
import os
import pickle
import re
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import baseline  # noqa: E402
import common  # noqa: E402
from common import ACC_SCALE, ALS_LSB, FEATURES, GYR_SCALE, LABELS, OUT, ROOT, WIN  # noqa: E402
from features import features_matrix  # noqa: E402

N_GOLDEN = 50


def f32(v):
    s = f"{float(np.float32(v)):.9g}"
    if not re.search(r"[.eEn]", s):
        s += ".0"
    return s + "f"


def arr(name, ctype, vals, per_line=8, fmt=f32):
    vals = list(vals)
    body = ",\n".join("    " + ", ".join(fmt(v) for v in vals[i:i + per_line]) for i in range(0, len(vals), per_line))
    return f"static const {ctype} {name}[{len(vals)}] = {{\n{body}\n}};\n"


def check_dsp_constants():
    path = os.path.join(ROOT, "src", "dsp", "features.h")
    text = open(path, encoding="utf-8").read()
    want = {"FEAT_N": len(FEATURES), "FEAT_WIN": WIN, "FEAT_NFFT": common.NFFT, "FEAT_LOW_K0": common.LOW_BINS[0],
            "FEAT_LOW_K1": common.LOW_BINS[1], "FEAT_HIGH_K0": common.HIGH_BINS[0],
            "FEAT_HIGH_K1": common.HIGH_BINS[1], "FEAT_TILT_N": common.TILT_N, "FEAT_PS_NEAR": common.PS_NEAR}
    for k, v in want.items():
        m = re.search(rf"#define\s+{k}\s+(\d+)", text)
        if not m or int(m.group(1)) != v:
            sys.exit(f"src/dsp/features.h: {k} must be {v} (ml/common.py)")
    m = re.search(r"#define\s+FEAT_PEAK_G\s+([0-9.]+)f", text)
    if not m or abs(float(m.group(1)) * common.G - common.PEAK_THRESH) > 1e-6:
        sys.exit("src/dsp/features.h: FEAT_PEAK_G must be 1.5")


def params_header(m, th, version):
    names = ",\n".join(f'    "{n}"' for n in FEATURES)
    classes = ", ".join(f'"{c}"' for c in LABELS)
    out = ["/* Generated by ml/export_c.py. Do not edit. */",
           "#ifndef MODEL_PARAMS_H", "#define MODEL_PARAMS_H", "",
           f"#define MODEL_AVAILABLE   {1 if m else 0}",
           f"#define MODEL_N_FEATURES  {len(FEATURES)}",
           f"#define MODEL_N_CLASSES   {len(LABELS)}",
           f'#define MODEL_VERSION     "{version}"',
           f'#define MODEL_TRAINED     "{datetime.date.today().isoformat() if m else "none"}"', ""]
    for k in baseline.KEYS:
        out.append(f"#define BASELINE_{k.upper():9s} {f32(th[k]) if th else '0.0f'}  /* {baseline.FEAT[k]} */")
    out += ["", "#ifdef MODEL_DEFINE_TABLES",
            f"static const char *const model_class_names[MODEL_N_CLASSES] = {{{classes}}};",
            f"static const char *const model_feature_names[MODEL_N_FEATURES] = {{\n{names}\n}};"]
    if m:
        out.append(arr("model_feat_mean", "float", m["mu"]))
        out.append(arr("model_feat_std", "float", m["sd"]))
    else:
        out.append(arr("model_feat_mean", "float", [0.0] * len(FEATURES)))
        out.append(arr("model_feat_std", "float", [1.0] * len(FEATURES)))
    out += ["#endif /* MODEL_DEFINE_TABLES */", "", "#endif /* MODEL_PARAMS_H */", ""]
    return "\n".join(out)


def weights_header(m):
    out = ["/* Generated by ml/export_c.py. Do not edit. */", "#ifndef MODEL_WEIGHTS_H", "#define MODEL_WEIGHTS_H",
           "", "#include <stdint.h>", ""]
    if not m:
        out += ["#define MLP_N_LAYERS 0", "", "#endif /* MODEL_WEIGHTS_H */", ""]
        return "\n".join(out)
    mlp = m["mlp"]
    dims = [mlp.coefs_[0].shape[0]] + [c.shape[1] for c in mlp.coefs_]
    out += [f"#define MLP_N_LAYERS {len(mlp.coefs_)}", f"#define MLP_MAX_WIDTH {max(dims)}", "",
            "#ifdef MODEL_DEFINE_TABLES",
            f"static const uint16_t mlp_dims[MLP_N_LAYERS + 1] = {{{', '.join(map(str, dims))}}};"]
    for i, (W, b) in enumerate(zip(mlp.coefs_, mlp.intercepts_)):
        out.append(f"/* layer {i}: {W.shape[0]} -> {W.shape[1]}, "
                   f"{'ReLU' if i < len(mlp.coefs_) - 1 else 'softmax'} */")
        out.append(arr(f"mlp_w{i}", "float", W.T.reshape(-1)))
        out.append(arr(f"mlp_b{i}", "float", b))
    ws = ", ".join(f"mlp_w{i}" for i in range(len(mlp.coefs_)))
    bs = ", ".join(f"mlp_b{i}" for i in range(len(mlp.coefs_)))
    out += [f"static const float *const mlp_w[MLP_N_LAYERS] = {{{ws}}};",
            f"static const float *const mlp_b[MLP_N_LAYERS] = {{{bs}}};",
            "#endif /* MODEL_DEFINE_TABLES */", "", "#endif /* MODEL_WEIGHTS_H */", ""]
    return "\n".join(out)


def golden_header(m, th):
    out = ["/* Generated by ml/export_c.py. Do not edit. Test windows for `selftest model` (AC-3). */",
           "#ifndef GOLDEN_VECTORS_H", "#define GOLDEN_VECTORS_H", "", "#include <stdint.h>", ""]
    if not m:
        out += ["#define GOLDEN_N 0", "", "#endif /* GOLDEN_VECTORS_H */", ""]
        return "\n".join(out)
    d = np.load(os.path.join(OUT, "windows.npz"))
    te = np.flatnonzero(d["split"] == "test")
    # Spread over classes and over time: every k-th test window of each class.
    pick = []
    for c in range(len(LABELS)):
        idx = te[d["y"][te] == c]
        k = max(1, len(idx) // (N_GOLDEN // len(LABELS) + 1))
        pick += list(idx[::k][:N_GOLDEN // len(LABELS)])
    rest = [i for i in te if i not in set(pick)]
    pick = (pick + rest)[:N_GOLDEN]
    X = d["X"][pick].astype(np.float64)
    imu = np.round(np.concatenate([X[:, :, 0:3] * ACC_SCALE, X[:, :, 3:6] * GYR_SCALE], axis=2)).astype(np.int64)
    als = np.round(X[:, :, 6] / ALS_LSB).astype(np.int64)
    ps = np.where(X[:, :, 8] > 0.5, X[:, :, 7], -(X[:, :, 7] + 1)).astype(np.int64)
    for name, v, lo, hi in (("imu", imu, -32768, 32767), ("als", als, 0, 65535), ("ps", ps, -32768, 32767)):
        if v.min() < lo or v.max() > hi:  # would wrap silently in the C array
            sys.exit(f"golden {name} values {v.min()}..{v.max()} do not fit the C type ({lo}..{hi})")
    # Recompute from the exact integers, as the firmware will.
    Xr = np.concatenate([imu[:, :, 0:3] / ACC_SCALE, imu[:, :, 3:6] / GYR_SCALE, (als * ALS_LSB)[:, :, None],
                         np.abs(np.where(ps < 0, ps + 1, ps))[:, :, None], (ps >= 0)[:, :, None]], axis=2)
    F = features_matrix(Xr)
    P = m["mlp"].predict_proba((F - m["mu"]) / m["sd"])
    B = baseline.predict(F, th)
    n = len(pick)
    out += [f"#define GOLDEN_N {n}", f"#define GOLDEN_WIN {WIN}", "",
            "/* imu: ax, ay, az (m/s^2 x 800), gx, gy, gz (deg/s x 60); als: lux / 0.35; "
            "ps: raw, or -(raw + 1) when not valid */",
            "#ifdef GOLDEN_DEFINE_TABLES"]
    out.append(arr("golden_imu", "int16_t", imu.reshape(-1), per_line=12, fmt=str).replace(
        f"golden_imu[{imu.size}]", f"golden_imu[GOLDEN_N * GOLDEN_WIN * 6]"))
    out.append(arr("golden_als", "uint16_t", als.reshape(-1), per_line=16, fmt=str).replace(
        f"golden_als[{als.size}]", "golden_als[GOLDEN_N * GOLDEN_WIN]"))
    out.append(arr("golden_ps", "int16_t", ps.reshape(-1), per_line=16, fmt=str).replace(
        f"golden_ps[{ps.size}]", "golden_ps[GOLDEN_N * GOLDEN_WIN]"))
    out.append(arr("golden_feat", "float", F.reshape(-1), per_line=6))
    out.append(arr("golden_prob", "float", P.reshape(-1), per_line=4))
    out.append(arr("golden_label", "uint8_t", d["y"][pick], per_line=25, fmt=str))
    out.append(arr("golden_base", "uint8_t", B, per_line=25, fmt=str))
    out += ["#endif /* GOLDEN_DEFINE_TABLES */", "", "#endif /* GOLDEN_VECTORS_H */", ""]
    return "\n".join(out), n


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--placeholder", action="store_true")
    ap.add_argument("--root", default=ROOT, help="write under this tree (for tests)")
    a = ap.parse_args()
    check_dsp_constants()
    m = th = None
    version = "none"
    if not a.placeholder:
        with open(os.path.join(OUT, "model.pkl"), "rb") as f:
            m = pickle.load(f)
        with open(os.path.join(OUT, "baseline.json"), encoding="utf-8") as f:
            th = json.load(f)
        h = hashlib.sha256()
        for c in m["mlp"].coefs_ + m["mlp"].intercepts_ + [m["mu"], m["sd"]]:
            h.update(np.asarray(c, dtype=np.float32).tobytes())
        h.update(json.dumps(th, sort_keys=True).encode())
        version = h.hexdigest()[:8]
    files = {os.path.join("src", "model", "model_params.h"): params_header(m, th, version),
             os.path.join("src", "model", "model_weights.h"): weights_header(m)}
    g = golden_header(m, th)
    files[os.path.join("test", "golden", "golden_vectors.h")] = g[0] if m else g
    for rel, text in files.items():
        p = os.path.join(a.root, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"wrote {rel} ({len(text) // 1024} KB)")
    print(f"model version {version}" + (f", {g[1]} golden windows" if m else " (placeholder)"))


if __name__ == "__main__":
    main()

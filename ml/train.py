"""Train the classifier and the baseline on the TRAIN sessions (PRD 7.3).

    .venv\\Scripts\\python ml\\train.py

Inputs: ml/out/features.csv from prepare.py. Model selection uses grouped
cross-validation over the training sessions only (GroupKFold by session; by
trial if there is a single training session), so the test session is never
looked at here.

  * MLP 42 -> 24 -> 16 -> 4 (ReLU, softmax), z-scored inputs; L2 alpha chosen
    by CV.
  * Decision tree (depth chosen by CV), for comparison only.
  * Baseline thresholds (baseline.py), tuned on all training windows.

Writes ml/out/model.pkl, ml/out/baseline.json and ml/reports/training.md.
"""
import csv
import json
import os
import pickle
import sys
import warnings

import numpy as np
import sklearn
from sklearn.exceptions import ConvergenceWarning
from sklearn.metrics import f1_score
from sklearn.model_selection import GroupKFold
from sklearn.neural_network import MLPClassifier
from sklearn.tree import DecisionTreeClassifier

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import baseline  # noqa: E402
from common import FEATURES, LABELS, OUT, REPORTS  # noqa: E402

HIDDEN = (24, 16)
ALPHAS = [1e-4, 1e-3, 1e-2, 1e-1, 1.0]
DEPTHS = [3, 4, 5, 6, 8]
SEED = 0


def load(path=os.path.join(OUT, "features.csv")):
    with open(path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    if not rows:
        sys.exit("no windows in features.csv: run ml/prepare.py first")
    meta = {k: np.array([r[k] for r in rows]) for k in ("split", "session", "trial", "t0_ms", "label")}
    F = np.array([[float(r[k]) for k in FEATURES] for r in rows])
    y = np.array([LABELS.index(r["label"]) for r in rows])
    return F, y, meta


def norm_params(F):
    mu = F.mean(axis=0)
    sd = F.std(axis=0)
    sd[sd < 1e-9] = 1.0
    return mu, sd


def make_mlp(alpha):
    return MLPClassifier(hidden_layer_sizes=HIDDEN, activation="relu", alpha=alpha, max_iter=3000,
                         random_state=SEED, solver="adam", learning_rate_init=1e-3, n_iter_no_change=50, tol=1e-5)


def cv_score(make, F, y, groups):
    k = min(5, len(set(groups)))
    if k < 2:
        return float("nan")
    scores = []
    for tr, va in GroupKFold(n_splits=k).split(F, y, groups):
        mu, sd = norm_params(F[tr])
        m = make()
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", ConvergenceWarning)
            m.fit((F[tr] - mu) / sd, y[tr])
        scores.append(f1_score(y[va], m.predict((F[va] - mu) / sd), average="macro", labels=[0, 1, 2, 3],
                               zero_division=0))
    return float(np.mean(scores))


def main():
    F, y, meta = load()
    tr = meta["split"] == "train"
    Ft, yt = F[tr], y[tr]
    sessions = meta["session"][tr]
    groups = sessions if len(set(sessions)) >= 2 else np.char.add(sessions, meta["trial"][tr])
    group_kind = "session" if len(set(sessions)) >= 2 else "trial (only one training session)"

    mlp_cv = {a: cv_score(lambda a=a: make_mlp(a), Ft, yt, groups) for a in ALPHAS}
    tree_cv = {d: cv_score(lambda d=d: DecisionTreeClassifier(max_depth=d, random_state=SEED), Ft, yt, groups)
               for d in DEPTHS}
    best_alpha = max(ALPHAS, key=lambda a: (np.nan_to_num(mlp_cv[a], nan=-1), -a))
    best_depth = max(DEPTHS, key=lambda d: (np.nan_to_num(tree_cv[d], nan=-1), -d))

    mu, sd = norm_params(Ft)
    mlp = make_mlp(best_alpha)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", ConvergenceWarning)
        mlp.fit((Ft - mu) / sd, yt)
    tree = DecisionTreeClassifier(max_depth=best_depth, random_state=SEED).fit((Ft - mu) / sd, yt)
    th, base_f1 = baseline.tune(Ft, yt)

    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "model.pkl"), "wb") as f:
        pickle.dump({"mlp": mlp, "tree": tree, "mu": mu, "sd": sd, "alpha": best_alpha, "depth": best_depth,
                     "features": FEATURES, "labels": LABELS, "sklearn": sklearn.__version__}, f)
    with open(os.path.join(OUT, "baseline.json"), "w", encoding="utf-8") as f:
        json.dump(th, f, indent=2)

    n_weights = sum(c.size for c in mlp.coefs_) + sum(b.size for b in mlp.intercepts_)
    lines = ["# Training report", "", "Generated by `ml/train.py`. Training sessions only; the test session is not "
             "used here.", "",
             f"Training windows: {len(yt)} from sessions {', '.join(sorted(set(sessions)))}. "
             f"Cross-validation groups: {group_kind}.", "",
             "## MLP (42 -> 24 -> 16 -> 4), cross-validated macro-F1 by L2 alpha", "",
             "| alpha | CV macro-F1 |", "|---|---|"]
    lines += [f"| {a:g} | {mlp_cv[a]:.3f} |" for a in ALPHAS]
    lines += ["", f"Chosen alpha {best_alpha:g}. Final fit: {mlp.n_iter_} iterations, {n_weights} parameters "
              f"({n_weights * 4} bytes as float32).", "",
              "## Decision tree (comparison), cross-validated macro-F1 by depth", "", "| depth | CV macro-F1 |",
              "|---|---|"]
    lines += [f"| {d} | {tree_cv[d]:.3f} |" for d in DEPTHS]
    lines += ["", f"Chosen depth {best_depth}.", "", "## Baseline thresholds (tuned on all training windows)", "",
              "| Threshold | Feature | Value |", "|---|---|---|"]
    lines += [f"| {k} | {baseline.FEAT[k]} | {th[k]:.4g} |" for k in baseline.KEYS]
    lines += ["", f"Baseline macro-F1 on the training windows (optimistic, tuned there): {base_f1:.3f}.", "",
              f"Versions: scikit-learn {sklearn.__version__}, numpy {np.__version__}."]
    os.makedirs(REPORTS, exist_ok=True)
    with open(os.path.join(REPORTS, "training.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"MLP alpha {best_alpha:g} (CV macro-F1 {mlp_cv[best_alpha]:.3f}), tree depth {best_depth} "
          f"({tree_cv[best_depth]:.3f}), baseline train macro-F1 {base_f1:.3f}; {n_weights} weights")


if __name__ == "__main__":
    main()

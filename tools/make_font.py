"""Generate the LCD bitmap fonts (src/ui/font_data.h) from DejaVu Sans Mono.

    .venv\\Scripts\\python tools\\make_font.py [--preview "Text"]

DejaVu Sans Mono ships with matplotlib (mpl-data/fonts/ttf, license file
LICENSE_DEJAVU: Bitstream Vera / DejaVu terms, free to use, modify and embed
with the notice kept; see NOTICE.md). Each printable ASCII glyph (32..126)
is rendered without antialiasing into a fixed cell on a common baseline and
stored 1 bit per pixel, row-major, MSB = leftmost pixel.
"""
import argparse
import os

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from matplotlib import font_manager  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = os.path.join(matplotlib.get_data_path(), "fonts", "ttf", "DejaVuSansMono.ttf")
BOLD = os.path.join(matplotlib.get_data_path(), "fonts", "ttf", "DejaVuSansMono-Bold.ttf")
FIRST, LAST = 32, 126
# name, cell width, cell height, font file, em size in px, baseline px from the cell bottom
SIZES = [("font8x16", 8, 16, FONT, 13.0, 4), ("font12x24", 12, 24, BOLD, 19.5, 5)]


def render(ch, w, h, path, em_px, base):
    prop = font_manager.FontProperties(fname=path, size=em_px * 72.0 / 100.0)
    fig = plt.figure(figsize=(w / 100.0, h / 100.0), dpi=100)
    fig.patch.set_facecolor("white")
    t = fig.text(0.0, base / h, ch, fontproperties=prop, color="black", va="baseline", ha="left")
    t.set_antialiased(False)
    fig.canvas.draw()
    img = np.asarray(fig.canvas.buffer_rgba())[:, :, 0]
    plt.close(fig)
    return img < 128


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", default="")
    a = ap.parse_args()
    out = ["/* Generated by tools/make_font.py from DejaVu Sans Mono (see NOTICE.md). Do not edit. */",
           "#ifndef FONT_DATA_H", "#define FONT_DATA_H", "", "#include <stdint.h>", "",
           f"#define FONT_FIRST {FIRST}", f"#define FONT_LAST  {LAST}", ""]
    for name, w, h, path, em, base in SIZES:
        bpr = (w + 7) // 8
        data = []
        for code in range(FIRST, LAST + 1):
            g = render(chr(code), w, h, path, em, base)
            for r in range(h):
                v = 0
                for c in range(w):
                    if g[r, c]:
                        v |= 1 << (bpr * 8 - 1 - c)
                data += [(v >> (8 * (bpr - 1 - k))) & 0xFF for k in range(bpr)]
            if a.preview and chr(code) in a.preview:
                print(f"{name} '{chr(code)}'")
                for r in range(h):
                    print("".join("#" if g[r, c] else "." for c in range(w)))
        rows = [", ".join(f"0x{b:02X}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
        out += [f"#define {name.upper()}_W {w}", f"#define {name.upper()}_H {h}",
                f"static const uint8_t {name}[{len(data)}] = {{", "    " + ",\n    ".join(rows), "};", ""]
    out += ["#endif /* FONT_DATA_H */", ""]
    dst = os.path.join(ROOT, "src", "ui", "font_data.h")
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"wrote {os.path.relpath(dst, ROOT)}")


if __name__ == "__main__":
    main()
